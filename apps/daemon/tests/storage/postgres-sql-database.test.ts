// SqlDatabase: the synchronous Postgres handle the daemon's stores run on.
// Needs the suite's Postgres (tests/global-setup-postgres.ts).

import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { appliedMigrationIds, runMigrations } from '../../src/storage/postgres/migrations.js';
import { isConstraintViolation, type SqlDatabase } from '../../src/storage/postgres/sql-database.js';
import { DAEMON_MIGRATIONS } from '../../src/db.js';
import { createTestDatabase, tableExists } from '../helpers/test-db.js';

let db: SqlDatabase;

beforeEach(() => {
  db = createTestDatabase({ migrate: false });
  db.exec(`
    CREATE TABLE items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT COLLATE "C" NOT NULL UNIQUE,
      size BIGINT,
      ratio DOUBLE PRECISION,
      body BYTEA,
      payload TEXT
    );
  `);
});

afterEach(() => {
  db.close();
});

describe('SqlDatabase', () => {
  it('runs parameterized statements with the better-sqlite3 call shapes', () => {
    const insert = db.prepare('INSERT INTO items (name, size, ratio, body) VALUES (?, ?, ?, ?)');
    expect(insert.run('a', 1_800_000_000_000, 0.5, Buffer.from('hi'))).toEqual({ changes: 1, lastInsertRowid: 0 });
    insert.run(['b', null, null, null]);
    db.prepare('INSERT INTO items (name, size) VALUES (@name, @size)').run({ name: 'c', size: 3 });

    const row = db.prepare('SELECT name, size AS sizeBytes, ratio, body FROM items WHERE name = ?').get('a') as {
      name: string; sizeBytes: number; ratio: number; body: Buffer;
    };
    expect(row).toEqual({ name: 'a', sizeBytes: 1_800_000_000_000, ratio: 0.5, body: Buffer.from('hi') });
    expect(Buffer.isBuffer(row.body)).toBe(true);
    expect(db.prepare('SELECT name FROM items WHERE name = ?').get('missing')).toBeUndefined();
    expect(db.prepare('SELECT count(*) AS n, sum(size) AS total FROM items').get()).toEqual({ n: 3, total: 1_800_000_000_003 });
    expect([...db.prepare('SELECT name FROM items ORDER BY name').iterate()]).toEqual([
      { name: 'a' }, { name: 'b' }, { name: 'c' },
    ]);
    expect(db.prepare('UPDATE items SET size = 0 WHERE size IS NOT NULL').run().changes).toBe(2);
  });

  it('orders NULLs like SQLite and reports booleans as 0/1', () => {
    db.prepare('INSERT INTO items (name, size) VALUES (?, ?), (?, ?), (?, ?)').run('x', 2, 'y', null, 'z', 1);
    expect(db.prepare('SELECT name FROM items ORDER BY size').all()).toEqual([{ name: 'y' }, { name: 'z' }, { name: 'x' }]);
    expect(db.prepare('SELECT name FROM items ORDER BY size DESC').all()).toEqual([{ name: 'x' }, { name: 'z' }, { name: 'y' }]);
    expect(db.prepare('SELECT size IS NULL AS missing FROM items WHERE name = ?').get('y')).toEqual({ missing: 1 });
  });

  it('commits and rolls back transactions, nesting with savepoints', () => {
    const insert = db.prepare('INSERT INTO items (name) VALUES (?)');
    db.transaction(() => {
      insert.run('kept');
      expect(db.inTransaction).toBe(true);
      expect(() => db.transaction(() => {
        insert.run('inner');
        throw new Error('inner fails');
      })()).toThrow('inner fails');
    })();
    expect(() => db.transaction(() => {
      insert.run('dropped');
      throw new Error('outer fails');
    })()).toThrow('outer fails');
    expect(db.inTransaction).toBe(false);
    expect(db.prepare('SELECT name FROM items ORDER BY name').all()).toEqual([{ name: 'kept' }]);
  });

  it('keeps a transaction usable after a failed statement, like SQLite', () => {
    const insert = db.prepare('INSERT INTO items (name) VALUES (?)');
    db.transaction(() => {
      insert.run('one');
      let caught: unknown;
      try {
        insert.run('one');
      } catch (error) {
        caught = error;
      }
      expect(isConstraintViolation(caught)).toBe(true);
      expect((caught as { code?: string }).code).toBe('23505');
      insert.run('two');
    })();
    expect(db.prepare('SELECT count(*) AS n FROM items').get()).toEqual({ n: 2 });
  });

  it('rejects transaction functions that return a promise', () => {
    expect(() => db.transaction(async () => undefined)()).toThrow('cannot return a promise');
    expect(db.inTransaction).toBe(false);
  });

  it('fails fast on missing parameters', () => {
    expect(() => db.prepare('SELECT * FROM items WHERE name = ? AND size = ?').get('a')).toThrow(RangeError);
    expect(() => db.prepare('SELECT * FROM items WHERE name = @name').get({})).toThrow('Missing named parameter');
  });
});

describe('runMigrations', () => {
  it('applies pending migrations once, in order, and records them', () => {
    const calls: string[] = [];
    const migrations = [
      { id: 'a', up: (h: SqlDatabase) => { calls.push('a'); h.exec('CREATE TABLE m_a (id TEXT)'); } },
      { id: 'b', up: () => { calls.push('b'); } },
    ];
    expect(runMigrations(db, migrations).applied).toEqual(['a', 'b']);
    expect(runMigrations(db, migrations).applied).toEqual([]);
    expect(runMigrations(db, [...migrations, { id: 'c', up: () => { calls.push('c'); } }]).applied).toEqual(['c']);
    expect(calls).toEqual(['a', 'b', 'c']);
    expect(appliedMigrationIds(db)).toEqual(['a', 'b', 'c']);
  });

  it('rolls back every pending migration when one fails', () => {
    expect(() => runMigrations(db, [
      { id: 'ok', up: (h: SqlDatabase) => h.exec('CREATE TABLE m_ok (id TEXT)') },
      { id: 'bad', up: (h: SqlDatabase) => h.exec('CREATE TABLE m_ok (id TEXT)') },
    ])).toThrow();
    expect(tableExists(db, 'm_ok')).toBe(false);
    expect(appliedMigrationIds(db)).toEqual([]);
  });

  it('builds the full daemon schema and is idempotent', () => {
    runMigrations(db, DAEMON_MIGRATIONS);
    expect(appliedMigrationIds(db)).toEqual(DAEMON_MIGRATIONS.map((m) => m.id));
    for (const table of ['projects', 'conversations', 'messages', 'routines', 'installed_plugins', 'media_tasks']) {
      expect(tableExists(db, table)).toBe(true);
    }
    for (const migration of DAEMON_MIGRATIONS) migration.up(db);
  });
});
