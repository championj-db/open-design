// Plan §3.GG1 — inspectSqliteDatabase() pure helper (Postgres schema inventory).

import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { DAEMON_MIGRATIONS, migrate } from '../src/db.js';
import type { SqlDatabase } from '../src/storage/postgres/sql-database.js';
import { inspectSqliteDatabase } from '../src/storage/db-inspect.js';
import { createTestDatabase } from './helpers/test-db.js';

let db: SqlDatabase;

beforeEach(() => {
  db = createTestDatabase({ migrate: false });
});

afterEach(() => {
  db.close();
});

describe('inspectSqliteDatabase', () => {
  it('returns kind=postgres and the connection description', async () => {
    const report = await inspectSqliteDatabase({ db });
    expect(report.kind).toBe('postgres');
    expect(report.location).toBe(db.name);
  });

  it('reports schemaVersion as the number of applied migrations', async () => {
    migrate(db);
    const report = await inspectSqliteDatabase({ db });
    expect(report.schemaVersion).toBe(DAEMON_MIGRATIONS.length);
    expect(report.tables.some((t) => t.name === 'od_schema_migrations')).toBe(false);
  });

  it('reports schemaVersion=0 for a fresh schema', async () => {
    const report = await inspectSqliteDatabase({ db });
    expect(report.schemaVersion).toBe(0);
  });

  it('lists user tables with row counts', async () => {
    db.exec(`
      CREATE TABLE projects (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT);
      CREATE TABLE files    (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, path TEXT);
      INSERT INTO projects (name) VALUES ('alpha'), ('beta'), ('gamma');
      INSERT INTO files (path) VALUES ('a.txt'), ('b.txt');
    `);
    const report = await inspectSqliteDatabase({ db });
    const byName = Object.fromEntries(report.tables.map((t) => [t.name, t.rowCount]));
    expect(byName).toEqual({ projects: 3, files: 2 });
  });

  it('walks tables in lexicographic order', async () => {
    db.exec(`
      CREATE TABLE zebra (id BIGINT PRIMARY KEY);
      CREATE TABLE alpha (id BIGINT PRIMARY KEY);
      CREATE TABLE mango (id BIGINT PRIMARY KEY);
    `);
    const report = await inspectSqliteDatabase({ db });
    expect(report.tables.map((t) => t.name)).toEqual(['alpha', 'mango', 'zebra']);
  });

  it('sums the schema tables, indexes and TOAST into sizeBytes', async () => {
    db.exec('CREATE TABLE x (id BIGINT PRIMARY KEY); INSERT INTO x VALUES (1);');
    const report = await inspectSqliteDatabase({ db });
    expect(report.sizeBytes).toBeGreaterThan(0);
  });

  it('records generatedAt as a recent epoch ms', async () => {
    const before = Date.now();
    const report = await inspectSqliteDatabase({ db });
    const after = Date.now();
    expect(report.generatedAt).toBeGreaterThanOrEqual(before);
    expect(report.generatedAt).toBeLessThanOrEqual(after + 50);
  });

  it('handles an empty schema without error', async () => {
    const report = await inspectSqliteDatabase({ db });
    expect(report.tables).toEqual([]);
    expect(report.sizeBytes).toBeGreaterThanOrEqual(0);
  });
});
